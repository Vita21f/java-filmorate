CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR NOT NULL,
    login VARCHAR NOT NULL,
    name VARCHAR,
    birthday DATE
);

CREATE TABLE IF NOT EXISTS mpa (
    id BIGINT PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS genres (
    id BIGINT PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS films (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL,
    description VARCHAR(200),
    release_date DATE NOT NULL,
    duration INTEGER NOT NULL,
    mpa_id BIGINT NOT NULL,

    CONSTRAINT fk_films_mpa
       FOREIGN KEY (mpa_id) REFERENCES mpa (id),

    CONSTRAINT chk_films_duration
       CHECK (duration > 0)
);

CREATE TABLE IF NOT EXISTS film_genres (
    film_id BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,

    PRIMARY KEY (film_id, genre_id),

    CONSTRAINT fk_film_genres_film
       FOREIGN KEY (film_id) REFERENCES films (id)
       ON DELETE CASCADE,

    CONSTRAINT fk_film_genres_genre
       FOREIGN KEY (genre_id) REFERENCES genres (id)
);

CREATE TABLE IF NOT EXISTS likes (
    film_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,

    PRIMARY KEY (film_id, user_id),

    CONSTRAINT fk_likes_film
       FOREIGN KEY (film_id) REFERENCES films (id)
       ON DELETE CASCADE,

    CONSTRAINT fk_likes_user
       FOREIGN KEY (user_id) REFERENCES users (id)
       ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS friendship (
    user_id BIGINT NOT NULL,
    friend_id BIGINT NOT NULL,
    status VARCHAR NOT NULL,

    PRIMARY KEY (user_id, friend_id),

    CONSTRAINT fk_friendship_user
       FOREIGN KEY (user_id) REFERENCES users (id)
       ON DELETE CASCADE,

    CONSTRAINT fk_friendship_friend
       FOREIGN KEY (friend_id) REFERENCES users (id)
       ON DELETE CASCADE,

    CONSTRAINT chk_friendship_not_self
       CHECK (user_id <> friend_id),

    CONSTRAINT chk_friendship_status
       CHECK (status IN ('PENDING', 'CONFIRMED'))
);

